"""Test Case definitions aligned with OWASP Top 10 for LLM Applications."""
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, Optional
import uuid
from pydantic import BaseModel, Field


class OWASPCategory(str, Enum):
    """OWASP Top 10 for LLM Applications (2025/2026 taxonomy)."""
    LLM01_PROMPT_INJECTION = "LLM01: Prompt Injection"
    LLM02_INSECURE_OUTPUT = "LLM02: Insecure Output Handling"
    LLM03_TRAINING_POISONING = "LLM03: Training Data Poisoning"
    LLM04_MODEL_DOS = "LLM04: Model Denial of Service"
    LLM05_SUPPLY_CHAIN = "LLM05: Supply Chain Vulnerabilities"
    LLM06_SENSITIVE_INFO_DISCLOSURE = "LLM06: Sensitive Information Disclosure"
    LLM07_INSECURE_PLUGIN_DESIGN = "LLM07: Insecure Plugin / Tool Design"
    LLM08_EXCESSIVE_AGENCY = "LLM08: Excessive Agency & Unconstrained Tool Abuse"
    LLM09_OVERRELIANCE = "LLM09: Overreliance"
    LLM10_MODEL_THEFT = "LLM10: Model Theft & System Fingerprinting"


class AttackTechnique(str, Enum):
    """Specific adversarial simulation techniques."""
    DIRECT_PROMPT_INJECTION = "direct_prompt_injection"
    INDIRECT_PROMPT_INJECTION = "indirect_prompt_injection"
    GOAL_HIJACKING = "goal_hijacking"
    DELIMITER_OVERRIDE = "delimiter_override"
    VIRTUAL_ROLE_PLAY = "virtual_role_play"
    TOKEN_SMUGGLING = "token_smuggling"
    UNAUTHORIZED_TOOL_INVOCATION = "unauthorized_tool_invocation"
    PRIVILEGE_ESCALATION = "privilege_escalation"
    PARAMETER_TAMPERING = "parameter_tampering"
    SYSTEM_PROMPT_EXTRACTION = "system_prompt_extraction"
    RAG_DATA_EXFILTRATION = "rag_data_exfiltration"
    MEM_LEAK_INSPECTION = "mem_leak_inspection"
    CANARY_EXTRACTION = "canary_extraction"


class SeverityLevel(str, Enum):
    """Vulnerability severity levels."""
    INFO = "INFO"
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class TestStatus(str, Enum):
    """Execution status of a security test case."""
    __test__ = False
    PENDING = "PENDING"
    IN_PROGRESS = "IN_PROGRESS"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"


class TestCase(BaseModel):
    """Individual security test case generated by red teaming agents."""
    __test__ = False
    test_id: str = Field(default_factory=lambda: f"test_{uuid.uuid4().hex[:8]}")
    category: OWASPCategory = Field(..., description="OWASP LLM category")
    technique: AttackTechnique = Field(..., description="Simulated attack technique")
    assigned_agent: str = Field(..., description="Specialist agent handling this case")
    
    title: str = Field(..., description="Brief human-readable title of the test")
    objective: str = Field(..., description="Clear verification objective")
    prompt_payload: str = Field(..., description="Input string / probe passed to target")
    
    target_tool_name: Optional[str] = Field(
        default=None,
        description="Target tool under test if technique involves tool abuse"
    )
    expected_defense: str = Field(
        default="Target should refuse unauthorized instructions and preserve boundaries.",
        description="Expected behavior of a properly hardened agent"
    )
    
    status: TestStatus = Field(default=TestStatus.PENDING)
    iteration: int = Field(default=1, description="Adaptive feedback loop iteration counter")
    max_iterations: int = Field(default=3, description="Max refinement iterations")
    
    metadata: Dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
